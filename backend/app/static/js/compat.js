/* ComfyOS – compatibility for older devices (old iPad/iPhone with iOS 12, old Android browsers).
   Loaded as the first script and only adds what is missing:
   - Pointer events from touch or mouse events (without them nothing could be operated in the floor plan, in Flow
     and at the sliders; the whole interface only listens to pointer events).
   - setPointerCapture/releasePointerCapture as an empty function. Touch events always go to the element the
     finger was put down on anyway – that is exactly the behaviour of capture.
   - ResizeObserver, Object.fromEntries, Array.flatMap.
   - Gaps in flex containers: Safari up to 14.0 (iPadOS 13) does not know `gap` there. Then <html> gets the class
     `no-flexgap`, and the fallback rules from compat.css (generated by dev/make_compat_css.py) create the gaps
     through margins. compat.css is only loaded then – newer browsers never see the file.
   - iPad (since 0.24.5): `shrink-to-fit=no` in the viewport, so Safari never zooms the page out on its own.
   None of this overwrites an existing implementation. */
(function () {
  'use strict'

  /* ---------- Flex gap: measure instead of guessing – two empty children in a column with a 1 px gap are 1 px high */
  function flexGapWorks() {
    var box = document.createElement('div')
    box.style.cssText = 'display:flex;flex-direction:column;row-gap:1px;position:absolute;visibility:hidden'
    box.appendChild(document.createElement('div'))
    box.appendChild(document.createElement('div'))
    document.documentElement.appendChild(box)
    var works = box.scrollHeight === 1
    document.documentElement.removeChild(box)
    return works
  }
  /* Text right next to an element (icon + label in a button): CSS does not reach text nodes, so
     the elements next to it get a mark – .fg-a = text follows, .fg-b = text comes before. compat.css
     gives them the gap of their container. Checked after changes to the document, at most every 200 ms. */
  function markTextNeighbours() {
    if (!document.body) return
    var walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT, null, false)
    var flex = [], known = [], node
    // Is the element a flex container? (measured once per element)
    var isFlex = function (el) {
      var i = known.indexOf(el)
      if (i < 0) { i = known.push(el) - 1; flex[i] = /flex/.test(getComputedStyle(el).display) }
      return flex[i]
    }
    while ((node = walker.nextNode())) {
      var before = node.previousElementSibling, after = node.nextElementSibling
      if ((!before && !after) || !/\S/.test(node.nodeValue)) continue
      var parent = node.parentNode
      if (!parent || parent.nodeType !== 1 || !isFlex(parent)) continue
      if (before && before.classList) before.classList.add('fg-a')
      if (after && after.classList) after.classList.add('fg-b')
    }
  }
  // Mark text neighbours, and again on every change of the page (bundled, every 200 ms).
  function watchTextNeighbours() {
    var timer = 0
    var later = function () { if (!timer) timer = setTimeout(function () { timer = 0; markTextNeighbours() }, 200) }
    markTextNeighbours()
    if (window.MutationObserver) new MutationObserver(later).observe(document.body, { childList: true, subtree: true })
  }
  // For reproducing on a new browser (UI test, diagnosis): /?compat=nogap switches the fallback rules on.
  // There `gap` and the margins then apply at once – only useful together with the test that switches `gap` off.
  var forced = /[?&]compat=nogap\b/.test(location.search)
  // load compat.css with the same version mark as this script (after an update the browser reloads both)
  function loadCompatCss() {
    var own = document.currentScript || document.querySelector('script[src*="/static/js/compat.js"]')
    var version = own && own.src.indexOf('?') >= 0 ? own.src.slice(own.src.indexOf('?')) : ''
    var link = document.createElement('link')
    link.rel = 'stylesheet'
    link.href = '/static/compat.css' + version
    document.head.appendChild(link)
  }
  try {
    if (forced || !flexGapWorks()) {
      document.documentElement.classList.add('no-flexgap')
      loadCompatCss()
      if (document.body) watchTextNeighbours()
      else document.addEventListener('DOMContentLoaded', watchTextNeighbours)
    }
  } catch (e) { }

  /* ---------- No automatic zooming out on the iPad. Safari there shrinks a page whose content is wider than the screen until
     it fits – the page then is no longer at scale 1 and the bars that stay put while scrolling end up offset. `shrink-to-fit=no`
     switches that off. Only where WebKit's touch gestures exist (GestureEvent: every browser on iPhone and iPad, Safari on the
     Mac ignores the viewport anyway): Chrome reports the unknown key as an error in the console. */
  try {
    var viewport = document.querySelector('meta[name="viewport"]')
    if (window.GestureEvent && viewport && viewport.content.indexOf('shrink-to-fit') < 0) viewport.content += ',shrink-to-fit=no'
  } catch (e) { }   // without the meta tag nothing is to be done

  if (!Object.fromEntries) {
    Object.fromEntries = function (list) {
      var out = {}
      ;(list || []).forEach(function (e) { out[e[0]] = e[1] })
      return out
    }
  }

  if (!Array.prototype.flatMap) {
    Array.prototype.flatMap = function (fn, self) {
      var out = []
      for (var i = 0; i < this.length; i++) {
        var v = fn.call(self, this[i], i, this)
        if (Array.isArray(v)) out.push.apply(out, v)
        else out.push(v)
      }
      return out
    }
  }

  /* ---------- ResizeObserver: replacement through window size and lazy checking (once per second) */
  if (!window.ResizeObserver) {
    var watched = []
    var poll = null
    // Check the size of all observed elements and report changed ones.
    var checkAll = function () {
      watched.forEach(function (w) {
        var el = w.el, cw = el.clientWidth, ch = el.clientHeight
        if (cw === w.w && ch === w.h) return
        w.w = cw; w.h = ch
        try { w.cb([{ target: el, contentRect: { width: cw, height: ch } }]) } catch (e) { }
      })
    }
    window.addEventListener('resize', checkAll)
    window.addEventListener('orientationchange', function () { setTimeout(checkAll, 250) })
    // Replacement for ResizeObserver with the same interface (observe, unobserve, disconnect).
    var Fallback = function (cb) { this._cb = cb; this._own = [] }
    Fallback.prototype.observe = function (el) {
      if (!el) return
      var w = { el: el, cb: this._cb, w: el.clientWidth, h: el.clientHeight }
      this._own.push(w); watched.push(w)
      if (!poll) poll = setInterval(checkAll, 1000)
    }
    Fallback.prototype.unobserve = function (el) {
      watched = watched.filter(function (w) { return !(w.el === el && w.cb === this._cb) }, this)
    }
    Fallback.prototype.disconnect = function () {
      var own = this._own
      watched = watched.filter(function (w) { return own.indexOf(w) < 0 })
      this._own = []
    }
    window.ResizeObserver = Fallback
  }

  if (window.PointerEvent) return

  /* ---------- Pointer-Events nachbilden */
  if (window.Element && !Element.prototype.setPointerCapture) {
    Element.prototype.setPointerCapture = function () { }
    Element.prototype.releasePointerCapture = function () { }
    Element.prototype.hasPointerCapture = function () { return false }
  }

  var active = {}        // pointerId -> Zielelement (Finger bleibt bei seinem Startelement)
  var lastTouch = 0      // iOS additionally fires mouse events after a tap – we ignore those

  // Dispatch an emulated pointer event at the target; returns false if the page rejected it
  // (preventDefault).
  function send(type, src, target, info) {
    if (!target || !target.dispatchEvent) return true
    var ev
    try {
      ev = new CustomEvent(type, { bubbles: true, cancelable: true })
    } catch (e) {
      ev = document.createEvent('CustomEvent')
      ev.initCustomEvent(type, true, true, null)
    }
    ev.clientX = info.x; ev.clientY = info.y
    ev.pageX = info.px; ev.pageY = info.py
    ev.screenX = info.sx; ev.screenY = info.sy
    ev.pointerId = info.id
    ev.pointerType = info.kind
    ev.isPrimary = info.primary
    ev.button = info.kind === 'mouse' ? (src.button || 0) : 0
    ev.buttons = type === 'pointerup' || type === 'pointercancel' ? 0 : (info.kind === 'mouse' ? (src.buttons != null ? src.buttons : 1) : 1)
    ev.pressure = type === 'pointerup' || type === 'pointercancel' ? 0 : 0.5
    ev.width = ev.height = 1
    ev.shiftKey = !!src.shiftKey; ev.ctrlKey = !!src.ctrlKey; ev.altKey = !!src.altKey; ev.metaKey = !!src.metaKey
    return target.dispatchEvent(ev)
  }

  function touchInfo(t, primary) {
    return { x: t.clientX, y: t.clientY, px: t.pageX, py: t.pageY, sx: t.screenX, sy: t.screenY,
      id: t.identifier + 2, kind: 'touch', primary: primary }
  }

  // Finger touches down: pass it on as pointerdown and remember the start element of the finger.
  function onTouchStart(e) {
    lastTouch = Date.now()
    var keep = true
    for (var i = 0; i < e.changedTouches.length; i++) {
      var t = e.changedTouches[i]
      var target = t.target && t.target.nodeType === 1 ? t.target : e.target
      active[t.identifier + 2] = target
      if (!send('pointerdown', e, target, touchInfo(t, Object.keys(active).length === 1))) keep = false
    }
    // If a handler took over the gesture (preventDefault), the page must not scroll along.
    if (!keep && e.cancelable) e.preventDefault()
  }

  // Finger moves: pass it on as pointermove to its start element.
  function onTouchMove(e) {
    lastTouch = Date.now()
    var keep = true
    for (var i = 0; i < e.changedTouches.length; i++) {
      var t = e.changedTouches[i], target = active[t.identifier + 2]
      if (!target) continue
      if (!send('pointermove', e, target, touchInfo(t, false))) keep = false
    }
    if (!keep && e.cancelable) e.preventDefault()
  }

  // Finger lifts or the gesture is cancelled: pass it on as pointerup or pointercancel.
  function onTouchEnd(e) {
    lastTouch = Date.now()
    var type = e.type === 'touchcancel' ? 'pointercancel' : 'pointerup'
    for (var i = 0; i < e.changedTouches.length; i++) {
      var t = e.changedTouches[i], target = active[t.identifier + 2]
      if (!target) continue
      delete active[t.identifier + 2]
      send(type, e, target, touchInfo(t, false))
    }
  }

  function mouseInfo(e) {
    return { x: e.clientX, y: e.clientY, px: e.pageX, py: e.pageY, sx: e.screenX, sy: e.screenY,
      id: 1, kind: 'mouse', primary: true }
  }

  var mouseDown = null
  // Pass a mouse event on as a pointer event – except the substitute events iOS sends after a tap.
  function onMouse(e) {
    if (Date.now() - lastTouch < 800) return            // mouse substitute event after a tap
    var map = { mousedown: 'pointerdown', mousemove: 'pointermove', mouseup: 'pointerup',
      mouseover: 'pointerover', mouseout: 'pointerout', mouseenter: 'pointerenter', mouseleave: 'pointerleave' }
    var type = map[e.type]
    if (!type) return
    var target = e.target
    if (type === 'pointerdown') mouseDown = target
    else if (mouseDown && (type === 'pointermove' || type === 'pointerup')) target = mouseDown
    if (type === 'pointerup') mouseDown = null
    if (!send(type, e, target, mouseInfo(e)) && e.cancelable) e.preventDefault()
  }

  var opt = { capture: true, passive: false }
  try {
    document.addEventListener('touchstart', onTouchStart, opt)
  } catch (e) {
    opt = true   // very old browsers only know the boolean capture
    document.addEventListener('touchstart', onTouchStart, opt)
  }
  document.addEventListener('touchmove', onTouchMove, opt)
  document.addEventListener('touchend', onTouchEnd, opt)
  document.addEventListener('touchcancel', onTouchEnd, opt)
  ;['mousedown', 'mousemove', 'mouseup', 'mouseover', 'mouseout'].forEach(function (t) {
    document.addEventListener(t, onMouse, opt)
  })
  document.addEventListener('mouseleave', onMouse, true)
  document.addEventListener('mouseenter', onMouse, true)
})()

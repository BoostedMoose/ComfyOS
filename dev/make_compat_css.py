"""Generate fallback rules for old browsers: backend/app/static/compat.css from app.css.

    python dev/make_compat_css.py            # rewrite compat.css
    python dev/make_compat_css.py --check    # only check whether compat.css matches the state of app.css (test)

Why: Safari up to 14.0 (iPadOS 13) knows `gap` only in the grid, not in flex containers – there all elements stick
together. compat.js recognises that at the start and sets `html.no-flexgap`; only then do the rules from
compat.css apply, which create the same gap through margins of the children. Browsers with flex `gap` are not affected.

This is how it is translated (X = gap within the row, Y = gap between the rows):
  row               ->  every visible child after the first gets `margin-left: X`
  column            ->  every visible child after the first gets `margin-top: Y`
  row with wrapping ->  every child gets `margin-right: X; margin-bottom: Y`, the container compensates for that on
                        the right and at the bottom. If the container itself carries a margin, a background or
                        distributes its children to the edges (`justify-content: space-between`), the rule for the row applies.
                        Helper classes such as `.row.wrap` are on many elements with margins of their own – there the
                        compensation is left out (a gap then stays at the bottom and on the right).
Three special cases are added:
  * Children with `margin-left: auto` or `margin-top: auto` (they push themselves to the edge) and hidden children
    (`.hidden`) stay untouched.
  * `::before`/`::after` of a container are flex children too and get their gap.
  * CSS does not reach text right next to an element (icon + label in a button). compat.js therefore marks
    the elements next to it: `.fg-a` = text follows, `.fg-b` = text comes before.
If a later rule only sets direction or wrapping anew (`.row.wrap`, `.pv-tools`), it inherits the gap of the
base rule; the margins of the base rule are reset there.

No build step: compat.css lives in the repo. Whoever changes a `gap` in a flex container in app.css runs this
script; tests/core/test_compat.py reports if that was forgotten.
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

STATIC = Path(__file__).resolve().parents[1] / "backend" / "app" / "static"
SOURCE, TARGET = STATIC / "app.css", STATIC / "compat.css"
ROOT_CLASS = "html.no-flexgap"
# Classes that always appear together with other classes in the markup – they inherit `display`, `gap`, wrapping from them.
# Filled from the templates in static/js (companions): if `fp-tools` appears everywhere as `row wrap fp-tools`,
# `.row` and `.wrap` belong to it.
ALSO_HAS: dict[str, tuple[str, ...]] = {}
CONTAINER_BASES = (".row", ".wrap", ".between", ".pv-bar", ".pv-chip", ".chips", ".seg", ".btn", ".chip", ".card-head",
                   ".section-head", ".tile", ".field", ".badge")
UTILITIES = {".row", ".wrap", ".between", ".grow", ".g2", ".g6", ".g8"}   # Hilfsklassen: stehen an beliebigen Elementen
GAP_PROPS = ("gap", "row-gap", "column-gap")
FLOW_PROPS = ("flex-direction", "flex-flow", "flex-wrap")
VISIBLE = "> :not(.hidden) ~ :not(.hidden)"       # every visible child after a visible child
HEAD = """/* ComfyOS – fallback rules for browsers without `gap` in flex containers (Safari up to 14.0, iPadOS 13).
   GENERATED by dev/make_compat_css.py from app.css – do not edit by hand.
   Only applies with html.no-flexgap (set by compat.js if the browser needs it).
   .fg-a / .fg-b: elements marked by compat.js after or before which plain text stands. */
"""

Rule = tuple[str, str, dict[str, str]]          # (@media head or "", selector list, declarations)


def parse(text: str, media: str = "") -> list[Rule]:
    """Split CSS into rules – also those in @media and @supports blocks (their head is carried along)."""
    out: list[Rule] = []
    i = 0
    while i < len(text):
        j = text.find("{", i)
        if j < 0:
            break
        head = " ".join(text[i:j].split())
        depth, k = 1, j + 1
        while depth and k < len(text):
            depth += {"{": 1, "}": -1}.get(text[k], 0)
            k += 1
        body = text[j + 1:k - 1]
        if head.startswith(("@media", "@supports")):
            out += parse(body, head)
        elif not head.startswith("@"):
            decl: dict[str, str] = {}
            for part in body.split(";"):
                if ":" in part:
                    name, value = part.split(":", 1)
                    decl[name.strip()] = " ".join(value.split())
            out.append((media, head, decl))
        i = k
    return out


def companions(scripts: list[Path]) -> dict[str, tuple[str, ...]]:
    """Read from the templates which container classes always accompany a class: {".fp-tools": (".row", ".wrap")}.
    Only what is in every `class="…"` with this class counts – a class that also appears alone
    has no companions."""
    seen: dict[str, set[str]] = {}
    for script in scripts:
        for attr in re.findall(r'class="([^"]*)"', script.read_text(encoding="utf-8")):
            names = {"." + n for n in re.sub(r"\$\{[^}]*\}", " ", attr).split() if re.fullmatch(r"[\w-]+", n)}
            for name in names:
                others = names - {name}
                seen[name] = others if name not in seen else seen[name] & others
    return {name: tuple(sorted(c for c in others if c in CONTAINER_BASES))
            for name, others in seen.items() if name not in CONTAINER_BASES and any(c in CONTAINER_BASES for c in others)}


def last_compound(selector: str) -> str:
    """Last part of a selector – the one that describes the element itself (`.a .b.c` -> `.b.c`)."""
    return re.split(r"[\s>+~]+", selector.strip())[-1]


def context(selector: str) -> str:
    """Everything before the last part of a selector (`.a > .b.c` -> `.a >`) – the place where the rule applies."""
    selector = " ".join(selector.split())
    return selector[:len(selector) - len(last_compound(selector))].strip()


def classes(compound: str) -> set[str]:
    """Classes of a selector part, completed with the classes that always come along in the markup (ALSO_HAS)."""
    found = set(re.findall(r"\.[\w-]+", re.sub(r":not\([^)]*\)", "", compound)))
    return found | {extra for c in found for extra in ALSO_HAS.get(c, ())}


def tag(compound: str) -> str:
    """Elementname eines Selektor-Teils (`button.x` -> `button`, `.x` -> ``)."""
    return re.split(r"[.:\[#]", compound)[0]


def with_companions(selector: str) -> str:
    """Selector whose last part also names the companion classes (`.fl-cat` -> `.fl-cat.row.wrap`). Matches the same
    elements but weighs as much as the rules of the companion classes – otherwise their fallback rule would win."""
    own = last_compound(selector)
    extra = "".join(c for c in sorted(classes(own)) if c not in re.findall(r"\.[\w-]+", own))
    return selector + extra


class Sheet:
    """All rules of app.css with the question: what applies to this selector?"""

    def __init__(self, css: str):
        """Remove comments and split."""
        self.rules = parse(re.sub(r"/\*.*?\*/", "", css, flags=re.S))

    def lookup(self, selector: str, prop: str, skip: dict[str, str] | None = None) -> str | None:
        """Value of a property for the elements of a selector: the last rule with the same selector or one
        that names the same or fewer classes in the same place (or everywhere) (`.row.tight` inherits from `.row`). An
        approximation of the cascade – it is enough because containers almost always set their kind in their own rule; the
        rest is in ALSO_HAS. `skip`: declarations of a rule that does not count (question about the base rule)."""
        own = last_compound(selector)
        want, element, place = classes(own), tag(own), context(selector)
        found = None
        for _media, head, decl in self.rules:
            if prop not in decl or decl is skip:
                continue
            for part in (p.strip() for p in head.split(",")):
                other = last_compound(part)
                if "::" in other or ":before" in other or ":after" in other:
                    continue
                have = classes(other)
                inherits = bool(have) and have <= want and tag(other) in ("", element) and context(part) in ("", place)
                if part == selector or inherits:
                    found = decl[prop]
        return found

    def auto_margin_classes(self) -> list[str]:
        """Classes of elements that push themselves to the edge with `margin-left: auto` or `margin-top: auto`."""
        out: list[str] = []
        for _media, head, decl in self.rules:
            if "auto" in (decl.get("margin-left"), decl.get("margin-top")):
                for part in head.split(","):
                    out += sorted(re.findall(r"\.[\w-]+", last_compound(part)))
        return list(dict.fromkeys(out))

    def pseudo(self, selector: str) -> list[str]:
        """`before`/`after` if the container has such a pseudo-element in the flow (it then is a flex child)."""
        out = []
        for _media, head, decl in self.rules:
            for part in (p.strip() for p in head.split(",")):
                for which in ("before", "after"):
                    if part in (f"{selector}::{which}", f"{selector}:{which}") and "content" in decl \
                            and decl.get("position") not in ("absolute", "fixed") and which not in out:
                        out.append(which)
        return out

    def kind(self, selector: str, decl: dict[str, str], skip: dict[str, str] | None = None) -> str | None:
        """How a container arranges its children: `column`, `row`, `trailing` (row with wrapping: margins after
        every child, the container compensates) or `open` (the same without compensation, for helper classes) – None if
        it is not a flex container. With `skip` the question about the base rule applies."""
        def value(prop: str) -> str:
            return ("" if skip is not None else decl.get(prop, "")) or self.lookup(selector, prop, skip) or ""
        if "flex" not in value("display"):
            return None
        flow = " ".join(value(p) for p in FLOW_PROPS)
        if "column" in flow:
            return "column"
        boxed = any(self.lookup(selector, p, skip) for p in ("margin", "margin-bottom", "margin-right", "background", "border",
                                                             "border-bottom", "overflow", "overflow-x"))
        if "wrap" not in flow.replace("nowrap", "") or "space-between" in value("justify-content") or boxed:
            return "row"
        own = set(re.findall(r"\.[\w-]+", last_compound(selector)))
        return "open" if own <= UTILITIES else "trailing"


def gap_values(decl: dict[str, str], sheet: Sheet, selector: str) -> tuple[str | None, str | None]:
    """(gap between rows, gap within the row) for a selector: from the rule itself, otherwise inherited."""
    def one(prop: str) -> str | None:
        return decl.get(prop) or sheet.lookup(selector, prop)
    row = col = None
    both = one("gap")
    if both:
        parts = both.split()
        row, col = parts[0], parts[-1]
    return one("row-gap") or row, one("column-gap") or col


def zero(value: str | None) -> bool:
    """Is the gap empty or zero?"""
    return value is None or re.fullmatch(r"0(px|rem|em)?", value) is not None


def own_margins(decl: dict[str, str]) -> tuple[str, str]:
    """(right, bottom margin) a rule gives its container itself – from `margin` and the single values."""
    right = bottom = "0"
    parts = decl.get("margin", "").split()
    if parts:
        bottom = parts[2] if len(parts) > 2 else parts[0]
        right = parts[1] if len(parts) > 1 else parts[0]
    return decl.get("margin-right", right), decl.get("margin-bottom", bottom)


def build(css: str) -> str:
    """Content of compat.css for a state of app.css (and of the templates the companion classes come from)."""
    ALSO_HAS.clear()
    ALSO_HAS.update(companions(sorted((STATIC / "js").glob("*.js"))))
    sheet = Sheet(css)
    kids = VISIBLE + "".join(f":not({c})" for c in sheet.auto_margin_classes())   # equally heavy everywhere
    blocks: dict[str, list[str]] = {}
    for media, head, decl in sheet.rules:
        sets_gap = any(p in decl for p in GAP_PROPS)
        if not (sets_gap or any(p in decl for p in FLOW_PROPS)):
            continue
        for selector in (s.strip() for s in head.split(",")):
            if "::" in selector:
                continue
            row_gap, col_gap = gap_values(decl, sheet, selector)
            kind = sheet.kind(selector, decl)
            if kind is None or (zero(row_gap) and zero(col_gap)):
                continue                                    # grid (there every browser can do `gap`) or no gap
            target = f"{ROOT_CLASS} {with_companions(selector)}"
            lines = blocks.setdefault(media, [])
            # reset what a base rule set as margins for the same elements and that no longer applies here
            inherited = any(sheet.lookup(selector, p, skip=decl) for p in GAP_PROPS)
            base = sheet.kind(selector, decl, skip=decl) if inherited else None
            if base and base != kind:
                if base == "row":
                    lines.append(f"{target} {kids} {{ margin-left: 0; }} {target} > .fg-a {{ margin-right: 0; }} {target} > .fg-b {{ margin-left: 0; }}")
                elif base == "column":
                    lines.append(f"{target} {kids} {{ margin-top: 0; }} {target} > .fg-a {{ margin-bottom: 0; }} {target} > .fg-b {{ margin-top: 0; }}")
                else:
                    lines.append(f"{target} > * {{ margin-right: 0; margin-bottom: 0; }}")
                    if base == "trailing":
                        right, bottom = own_margins(decl)
                        lines.append(f"{target} {{ margin-right: {right}; margin-bottom: {bottom}; }}")
            if kind == "column" and not zero(row_gap):
                lines.append(f"{target} {kids} {{ margin-top: {row_gap}; }}")
                lines.append(f"{target} > .fg-a {{ margin-bottom: {row_gap}; }} {target} > .fg-b {{ margin-top: {row_gap}; }}")
                edge = ("bottom", "top", row_gap)
            elif kind in ("trailing", "open"):
                # a row rule for the same elements (e.g. `.row.g8` next to `.row.wrap.g8`) does not apply here
                lines.append(f"{target} {kids} {{ margin-left: 0; }}")
                lines.append(f"{target} > * {{ margin-right: {col_gap or 0}; margin-bottom: {row_gap or 0}; }}")
                if kind == "trailing":
                    lines.append(f"{target} {{ margin-right: -{col_gap or '0px'}; margin-bottom: -{row_gap or '0px'}; }}")
                if not zero(col_gap):
                    lines.append(f"{target} > .fg-b {{ margin-left: {col_gap}; }}")
                edge = None
            elif kind == "row" and not zero(col_gap):
                lines.append(f"{target} {kids} {{ margin-left: {col_gap}; }}")
                lines.append(f"{target} > .fg-a {{ margin-right: {col_gap}; }} {target} > .fg-b {{ margin-left: {col_gap}; }}")
                edge = ("right", "left", col_gap)
            else:
                edge = None
            if edge:
                for which in sheet.pseudo(selector):
                    lines.append(f"{target}::{which} {{ margin-{edge[0] if which == 'before' else edge[1]}: {edge[2]}; }}")
    out = [HEAD]
    for media, lines in blocks.items():
        if media:
            out.append(f"{media} {{\n" + "\n".join("  " + line for line in lines) + "\n}")
        else:
            out.append("\n".join(lines))
    return "\n".join(out) + "\n"


def main() -> int:
    """Write compat.css or (with --check) only compare."""
    wanted = build(SOURCE.read_text(encoding="utf-8"))
    if "--check" in sys.argv:
        current = TARGET.read_text(encoding="utf-8") if TARGET.exists() else ""
        if current != wanted:
            print("compat.css does not match app.css – run dev/make_compat_css.py")
            return 1
        print("compat.css is up to date")
        return 0
    TARGET.write_bytes(wanted.encode("utf-8"))
    print(f"{TARGET.name}: {wanted.count('{') - wanted.count('@media')} rules written")
    return 0


if __name__ == "__main__":
    sys.exit(main())
